import sympy as sp
import numpy as np
import matplotlib.pyplot as plt

x = sp.Symbol('x')

# Lagrange basis polynomial

def lagrange_basis(xs, k):
    """
    Calculates the L_k(x) basis polynomial.
    """
    result = 1

    for j in range(len(xs)):
        if j != k:
            result *= (x - xs[j]) / (xs[k] - xs[j])

    return result

# Lagrange interpolation


def lagrange_interpolation(xs, values):
    """
    Calculates the Lagrange interpolation polynomial.
    """
    polynomial = 0

    for k in range(len(xs)):
        basis = lagrange_basis(xs, k)
        polynomial += values[k] * basis

    return sp.expand(polynomial)

# Newton interpolation


def newton_interpolation(xs, values):
    """
    Calculates the Newton interpolation polynomial
    using divided differences.
    """

    n = len(xs)

    # First column of the divided difference table
    table = [values[:]]

    # Calculate the divided differences
    for order in range(1, n):
        column = []

        for i in range(n - order):
            numerator = table[order - 1][i + 1] - table[order - 1][i]
            denominator = xs[i + order] - xs[i]

            difference = numerator / denominator
            column.append(difference)

        table.append(column)

    # Build the Newton polynomial
    polynomial = table[0][0]
    product = 1

    for i in range(1, n):
        product *= (x - xs[i - 1])
        polynomial += table[i][0] * product

    return sp.expand(polynomial), table

# Hermite interpolation


def hermite_interpolation(xs, values, derivatives):
    """
    Calculates the Hermite interpolation polynomial.

    Hermite interpolation uses:
        f(x_i)
    and
        f'(x_i)

    at every interpolation point.
    """
    polynomial = 0

    for k in range(len(xs)):

        # Lagrange basis L_k(x)
        Lk = lagrange_basis(xs, k)

        # Calculate L'_k(x_k)
        derivative_at_xk = 0

        for j in range(len(xs)):
            if j != k:
                derivative_at_xk += 1 / (xs[k] - xs[j])

        # Hermite basis polynomials
        Hk = (
            1 - 2 * (x - xs[k]) * derivative_at_xk
        ) * Lk**2

        Hk_bar = (x - xs[k]) * Lk**2

        # Add the contribution of this point
        polynomial += values[k] * Hk
        polynomial += derivatives[k] * Hk_bar

    return sp.expand(polynomial)


# Study one function


def study_function(f, df, points):
    """
    Compares Lagrange, Newton and Hermite interpolation
    for a given function and a given number of points.
    """

    xs = [sp.nsimplify(point) for point in points]

    print("\n" + "=" * 50)
    print("Function :", f)
    print("Derivative:", df)
    print("Number of points:", len(xs))
    print("Points:", xs)

    # Calculate f(x_i)
    values = []

    for point in xs:
        values.append(f.subs(x, point))

    # Calculate f'(x_i)
    derivatives = []

    for point in xs:
        derivatives.append(df.subs(x, point))


    # Calculate the three interpolation polynomials


    lagrange_poly = lagrange_interpolation(xs, values)

    newton_poly, divided_table = newton_interpolation(
        xs, values
    )

    hermite_poly = hermite_interpolation(
        xs, values, derivatives
    )


    # Display the results

    print("\nLagrange polynomial:")
    print(sp.N(lagrange_poly, 5))

    print("\nNewton polynomial:")
    print(sp.N(newton_poly, 5))

    print("\nHermite polynomial:")
    print(sp.N(hermite_poly, 5))


    # Convert SymPy functions into numerical functions

    f_function = sp.lambdify(x, f, "numpy")
    lagrange_function = sp.lambdify(x, lagrange_poly, "numpy")
    newton_function = sp.lambdify(x, newton_poly, "numpy")
    hermite_function = sp.lambdify(x, hermite_poly, "numpy")

    # Range used for the graph
    xmin = float(min(xs))
    xmax = float(max(xs))

    margin = 0.2 * (xmax - xmin)

    x_values = np.linspace(
        xmin - margin,
        xmax + margin,
        500
    )

    # Calculate y-values
    y_original = f_function(x_values)
    y_lagrange = lagrange_function(x_values)
    y_newton = newton_function(x_values)
    y_hermite = hermite_function(x_values)

    # Values of the interpolation points
    y_points = [float(value) for value in values]


    # Plot

    plt.figure(figsize=(9, 6))

    plt.plot(
        x_values,
        y_original,
        linewidth=2,
        label="Original function"
    )

    plt.plot(
        x_values,
        y_lagrange,
        linewidth=2,
        label="Lagrange"
    )

    plt.plot(
        x_values,
        y_newton,
        "--",
        linewidth=2,
        label="Newton"
    )

    plt.plot(
        x_values,
        y_hermite,
        "--",
        linewidth=2,
        label="Hermite"
    )

    plt.scatter(
        [float(point) for point in xs],
        y_points,
        label="Interpolation points"
    )

    plt.title(
        "Interpolation with " + str(len(xs)) + " points"
    )

    plt.xlabel("x")
    plt.ylabel("y")

    plt.legend()
    plt.grid(True)
    plt.show()



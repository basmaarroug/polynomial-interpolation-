import math

def f(x):
    return math.exp(-x**2)

def trapezoidal(a, b, n):
    h = (b - a) / n

    S = f(a) + f(b)

    for i in range(1, n):
        x = a + i * h
        S = S + 2 * f(x)

    I = (h / 2) * S
    return I

